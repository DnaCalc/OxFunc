fn ef(x: f64) -> Ext80 {
    ext_from_f64(x)
}
fn horner_f(cs: &[f64], x: Ext80) -> Ext80 {
    let mut acc = ef(0.0);
    for &c in cs.iter().rev() {
        acc = ext_add(&ext_mul(&acc, &x, CW), &ef(c), CW);
    }
    acc
}
fn horner_80(cs: &[Ext80], x: Ext80) -> Ext80 {
    let mut acc = ef(0.0);
    for c in cs.iter().rev() {
        acc = ext_add(&ext_mul(&acc, &x, CW), c, CW);
    }
    acc
}
fn aabb_f64(x: f64) -> f64 {
    let xe = ef(x.abs());
    let z = ext_div(&ef(1.0), &ext_add(&ef(2.5), &ext_mul(&xe, &xe, CW), CW), CW);
    let t = ext_sub(&ext_mul(&ef(13.0), &z, CW), &ef(1.0), CW);
    let n = horner_f(&AA, z);
    let d = horner_f(&BB, z);
    let mut acc = ext_div(&n, &d, CW);
    acc = ext_add(&ext_mul(&acc, &t, CW), &ef(E2), CW);
    acc = ext_add(&ext_mul(&acc, &t, CW), &ef(E1), CW);
    acc = ext_add(&ext_mul(&acc, &t, CW), &ef(E0), CW);
    ext_to_f64(&ext_div(&acc, &xe, CW), CW)
}
fn aabb_80(x: f64) -> f64 {
    let xe = ef(x.abs());
    let z = ext_div(&ef(1.0), &ext_add(&ef(2.5), &ext_mul(&xe, &xe, CW), CW), CW);
    let t = ext_sub(&ext_mul(&ef(13.0), &z, CW), &ef(1.0), CW);
    let n = horner_80(&AA80, z);
    let d = horner_80(&BB80, z);
    let mut acc = ext_div(&n, &d, CW);
    acc = ext_add(&ext_mul(&acc, &t, CW), &E80[2], CW);
    acc = ext_add(&ext_mul(&acc, &t, CW), &E80[1], CW);
    acc = ext_add(&ext_mul(&acc, &t, CW), &E80[0], CW);
    ext_to_f64(&ext_div(&acc, &xe, CW), CW)
}
fn pqr_80(x: f64) -> f64 {
    let xe = ef(x.abs());
    let u = horner_80(&PP80, xe);
    let v = horner_80(&QQ80, xe);
    let t = ext_div(
        &ext_sub(&xe, &ef(3.75), CW),
        &ext_add(&xe, &ef(3.75), CW),
        CW,
    );
    let mut acc = ext_div(&u, &v, CW);
    for r in RR80.iter().rev() {
        acc = ext_add(&ext_mul(&acc, &t, CW), r, CW);
    }
    ext_to_f64(&acc, CW)
}
fn derfc0_80(x: f64) -> f64 {
    if x.abs() <= 2.0 {
        pqr_80(x)
    } else {
        aabb_80(x)
    }
}
fn qw(z: f64, ff: f64) -> f64 {
    let v = f::w_rn53(z) * ff;
    if v.abs() < f64::MIN_POSITIVE {
        0.0
    } else {
        v
    }
}

fn main() {
    let dir = env::args().nth(1).expect("dir");
    let rows = f::load_q_rows_tagged(&dir);
    let graphs: [(&str, fn(f64) -> f64); 5] = [
        ("AABB f64-wide x87", aabb_f64),
        ("AABB 80-bit", aabb_80),
        ("PQR80", pqr_80),
        ("DERFC0 80 PQR+AABB", derfc0_80),
        ("nswc_derfc0 native", f::nswc_derfc0),
    ];
    for (name, ev) in graphs {
        let mut m2 = (0usize, 0usize, 0u64, 0usize, 0usize);
        let mut mid = (0usize, 0usize, 0u64, 0usize, 0usize);
        for r in &rows {
            if r.z < 0.5 || r.z >= 4.0 {
                continue;
            }
            let qg = qw(r.z, ev(r.z));
            if !qg.is_finite() {
                continue;
            }
            let d = ulp_distance(qg, f64::from_bits(r.qbits)).unwrap_or(u64::MAX);
            if d > ULP_CAP {
                continue;
            }
            mid.1 += 1;
            if r.direct {
                mid.4 += 1;
            }
            if d == 0 {
                mid.0 += 1;
                if r.direct {
                    mid.3 += 1;
                }
            } else {
                mid.2 = mid.2.max(d);
            }
            if r.z >= 2.0 {
                m2.1 += 1;
                if r.direct {
                    m2.4 += 1;
                }
                if d == 0 {
                    m2.0 += 1;
                    if r.direct {
                        m2.3 += 1;
                    }
                } else {
                    m2.2 = m2.2.max(d);
                }
            }
        }
        println!(
            "{name:22} mid {a}/{b} max={c} d={d}/{e}  [2,4) {f}/{g} max={h} d={i}/{j}",
            a = mid.0,
            b = mid.1,
            c = mid.2,
            d = mid.3,
            e = mid.4,
            f = m2.0,
            g = m2.1,
            h = m2.2,
            i = m2.3,
            j = m2.4
        );
    }
}
