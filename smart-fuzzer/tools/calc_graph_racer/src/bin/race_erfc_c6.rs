fn ef(x: f64) -> Ext80 {
    ext_from_f64(x)
}
fn poke(x: f64, k: i32) -> f64 {
    let mut v = x;
    if k > 0 {
        for _ in 0..k {
            v = v.next_up();
        }
    } else {
        for _ in 0..(-k) {
            v = v.next_down();
        }
    }
    v
}
fn maybe(x: Ext80, mask: u32, bit: u32) -> Ext80 {
    if bit < 32 && mask & (1u32 << bit) != 0 {
        ef(ext_to_f64(&x, CW))
    } else {
        x
    }
}
fn cody(y: f64, c: &[f64; 9], d: &[f64; 8], mask: u32) -> f64 {
    let ye = ef(y.abs());
    let mut xnum = ext_mul(&ef(c[8]), &ye, CW);
    let mut xden = ye;
    xnum = maybe(xnum, mask, 0);
    xden = maybe(xden, mask, 1);
    for i in 0..7 {
        xnum = ext_mul(&ext_add(&xnum, &ef(c[i]), CW), &ye, CW);
        xden = ext_mul(&ext_add(&xden, &ef(d[i]), CW), &ye, CW);
        xnum = maybe(xnum, mask, 2 + 2 * i as u32);
        xden = maybe(xden, mask, 3 + 2 * i as u32);
    }
    let mut q = ext_div(
        &ext_add(&xnum, &ef(c[7]), CW),
        &ext_add(&xden, &ef(d[7]), CW),
        CW,
    );
    q = maybe(q, mask, 16);
    ext_to_f64(&q, CW)
}
fn polevl_mask(x: Ext80, coef: &[f64], mask: u32, mut bit: u32) -> (Ext80, u32) {
    let mut ans = ef(coef[0]);
    for &c in &coef[1..] {
        ans = ext_add(&ext_mul(&ans, &x, CW), &ef(c), CW);
        ans = maybe(ans, mask, bit);
        bit += 1;
    }
    (ans, bit)
}
fn p1evl_mask(x: Ext80, coef: &[f64], mask: u32, mut bit: u32) -> (Ext80, u32) {
    let mut ans = ext_add(&x, &ef(coef[0]), CW);
    ans = maybe(ans, mask, bit);
    bit += 1;
    for &c in &coef[1..] {
        ans = ext_add(&ext_mul(&ans, &x, CW), &ef(c), CW);
        ans = maybe(ans, mask, bit);
        bit += 1;
    }
    (ans, bit)
}
fn cephes_mask(x: f64, mask: u32) -> f64 {
    let ax = x.abs();
    let xe = ef(ax);
    let (num, den, bit0) = if ax < 8.0 {
        let (p, b) = polevl_mask(xe, &CEPHES_P, mask, 0);
        let (q, b) = p1evl_mask(xe, &CEPHES_Q, mask, b);
        (p, q, b)
    } else {
        let (r, b) = polevl_mask(xe, &CEPHES_R, mask, 0);
        let (s, b) = p1evl_mask(xe, &CEPHES_S, mask, b);
        (r, s, b)
    };
    let mut q = ext_div(&num, &den, CW);
    q = maybe(q, mask, bit0);
    ext_to_f64(&q, CW)
}
fn tail_f(z: f64) -> f64 {
    cephes_mask(z, if z < 6.1 { 0x24a5 } else { 0x5005 })
}
fn qw(z: f64, ff: f64) -> f64 {
    let v = f::w_rn53(z) * ff;
    if v.abs() < f64::MIN_POSITIVE {
        0.0
    } else {
        v
    }
}

fn main() {
    let dir = env::args().nth(1).expect("dir");
    let rows = f::load_q_rows_tagged(&dir);
    let mut jc = C0;
    jc[0] = poke(C0[0], 4);
    jc[1] = poke(C0[1], 1);
    jc[4] = poke(C0[4], -1);
    let mut jd = D0;
    jd[0] = poke(D0[0], -1);
    jd[4] = poke(D0[4], -1);

    let mids: [(&str, Box<dyn Fn(f64) -> f64>); 4] = [
        ("CR0", Box::new(|z| cody(z, &C0, &D0, 0))),
        ("0x74", Box::new(|z| cody(z, &C0, &D0, 0x74))),
        ("0x210", Box::new(|z| cody(z, &C0, &D0, 0x210))),
        ("j3432", Box::new(|z| cody(z, &jc, &jd, 0))),
    ];
    println!("compose mid z<4 + 24a5-then-5005@6.1 tail (bars mid F_or 2976 / tail 1379 / mixed 2976+1370)");
    for (name, mid) in &mids {
        let mut qe = 0usize;
        let mut fe_m = 0usize;
        let mut fe_t = 0usize;
        let mut fd_m = 0usize;
        let mut fd_t = 0usize;
        let mut q_m = 0usize;
        let mut q_t = 0usize;
        for r in &rows {
            if r.z < 0.5 {
                continue;
            }
            let ff = if r.z < 4.0 { mid(r.z) } else { tail_f(r.z) };
            if ulp_distance(qw(r.z, ff), f64::from_bits(r.qbits)).unwrap_or(99) == 0 {
                qe += 1;
                if r.z < 4.0 {
                    q_m += 1;
                } else {
                    q_t += 1;
                }
            }
            if let Some(fo) = f::f_or(r.z, r.qbits) {
                if ulp_distance(ff, fo).unwrap_or(99) == 0 {
                    if r.z < 4.0 {
                        fe_m += 1;
                        if r.direct {
                            fd_m += 1;
                        }
                    } else {
                        fe_t += 1;
                        if r.direct {
                            fd_t += 1;
                        }
                    }
                }
            }
        }
        println!(
            "  {name:6} Q tot={qe} mid={q_m} tail={q_t}  F_or mid={fe_m} d={fd_m} tail={fe_t} d={fd_t} tot={}",
            fe_m + fe_t
        );
    }
}
