fn ef(x: f64) -> Ext80 { ext_from_f64(x) }
fn horner_f64(cs: &[f64], x: f64) -> f64 {
    let mut acc = 0.0;
    for &c in cs.iter().rev() { acc = acc * x + c; }
    acc
}
fn dcsevl_x87(x: f64, cs: &[f64], n: usize) -> f64 {
    let twox = ext_add(&ef(x), &ef(x), CW);
    let mut b2 = ef(0.0);
    let mut b1 = ef(0.0);
    let mut b0 = ef(0.0);
    for i in (0..n).rev() {
        b2 = b1;
        b1 = b0;
        b0 = ext_add(&ext_sub(&ext_mul(&twox, &b1, CW), &b2, CW), &ef(cs[i]), CW);
    }
    ext_to_f64(&ext_mul(&ef(0.5), &ext_sub(&b0, &b2, CW), CW), CW)
}
fn math77_f(y: f64, n_erc2: usize, n_erfcc: usize) -> f64 {
    let y = y.abs();
    if y <= 0.5 { return f64::NAN; }
    if y <= 1.0 { return horner_f64(&PS, y) / horner_f64(&QS, y); }
    let ysq = y * y;
    let cheb = if ysq <= 4.0 {
        dcsevl_x87((8.0 / ysq - 5.0) / 3.0, &ERC2CS, n_erc2.min(ERC2CS.len()))
    } else {
        dcsevl_x87(8.0 / ysq - 1.0, &ERFCCS, n_erfcc.min(ERFCCS.len()))
    };
    cheb / y
}
fn qw(z: f64, ff: f64) -> f64 {
    let v = f::w_rn53(z) * ff;
    if v.abs() < f64::MIN_POSITIVE { 0.0 } else { v }
}
#[derive(Default)]
struct Acc { exact: usize, n: usize, max_ulp: u64, dmid: usize, dn: usize }
impl Acc {
    fn add(&mut self, d: u64, direct: bool) {
        self.n += 1;
        if direct { self.dn += 1; }
        if d == 0 { self.exact += 1; if direct { self.dmid += 1; } }
        else { self.max_ulp = self.max_ulp.max(d); }
    }
}
fn fmt(a: &Acc) -> String {
    format!("{}/{} max={} d={}/{}", a.exact, a.n, a.max_ulp, a.dmid, a.dn)
}
fn score(rows: &[f::QRow], eval: impl Fn(f64) -> f64) -> (Acc, Acc) {
    let mut mid = Acc::default();
    let mut tail = Acc::default();
    for r in rows {
        if r.z < 0.5 { continue; }
        let qg = eval(r.z);
        if !qg.is_finite() { continue; }
        let d = ulp_distance(qg, f64::from_bits(r.qbits)).unwrap_or(u64::MAX);
        if d > ULP_CAP { continue; }
        if r.z < 4.0 { mid.add(d, r.direct); } else { tail.add(d, r.direct); }
    }
    (mid, tail)
}
fn main() {
    let dir = env::args().nth(1).expect("dir");
    let rows = f::load_q_rows_tagged(&dir);
    println!("## MATH77 mask-0 Q=w*F");
    for (n2, ninf) in [(8usize,8usize),(12,12),(16,16),(24,24),(24,59),(49,59)] {
        let (m,t) = score(&rows, |z| qw(z, math77_f(z, n2, ninf)));
        println!("n_erc2={n2:2} n_erfcc={ninf:2} mid {} tail {}", fmt(&m), fmt(&t));
    }
    println!("\n## piecewise Cody-native-erfcx z<2 else MATH77 n16");
    let (m,t) = score(&rows, |z| {
        if z < 2.0 { qw(z, f::cody_erfcx_f(z)) } else { qw(z, math77_f(z, 16, 16)) }
    });
    println!("cody-native/<2 MATH77n16 mid {} tail {}", fmt(&m), fmt(&t));
    let (m,t) = score(&rows, |z| {
        if z < 4.0 { qw(z, f::cody_erfcx_f(z)) } else { qw(z, math77_f(z, 16, 16)) }
    });
    println!("cody-native/<4 MATH77n16 mid {} tail {}", fmt(&m), fmt(&t));
}
